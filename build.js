// Runs on Vercel (and locally with `node build.js`): writes config.js from environment variables.
// Locally it also reads a .env file if present. If the variables are missing, config.js is left untouched.
const fs = require('fs');

try {
  for (const line of fs.readFileSync('.env', 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#') && process.env[m[1]] === undefined) {
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
  }
} catch { /* no .env file: fine on Vercel */ }

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_ANON_KEY;
const cur = process.env.CURRENCY || 'Rs';

if (!url || !key) {
  console.warn('build.js: SUPABASE_URL / SUPABASE_ANON_KEY not set — keeping existing config.js');
  process.exit(0);
}
fs.writeFileSync('config.js',
  `// Generated by build.js from environment variables. Do not edit.\nwindow.APP_CONFIG = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key, CURRENCY: cur }, null, 2)};\n`);
console.log('build.js: config.js written for', url);
